MAX_BRANCH_SUFFIX = 20
AI_NOTICE = (
    "> [!WARNING]\n"
    "> These changes were generated by an AI model and validated only to the extent that each"
    " patch applies cleanly and the changed files still parse. They have **not** been compiled,"
    " type-checked or tested. A human must review every change before merging."
)


class PullRequestError(Exception):
    """User-facing failure with a stable, distinct code."""

    def __init__(
        self,
        code: str,
        message: str,
        *,
        http_status: int = 409,
        details: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.http_status = http_status
        self.details = details or {}


@dataclass
class FixGroup:
    """Suggestions that share one generated patch (a grouped LLM request)."""

    suggestions: list[FixSuggestion]
    findings: list[Finding]
    patch: str

    @property
    def suggestion_ids(self) -> list[int]:
        return sorted(s.id for s in self.suggestions)

    @property
    def paths(self) -> list[str]:
        return patch_paths(self.patch)


@dataclass
class PatchCheck:
    suggestion_ids: list[int]
    paths: list[str]
    status: str  # applies | no_longer_applies | conflicts | syntax_error
    detail: str | None = None


@dataclass
class PullRequestPlan:
    repo_full_name: str
    head_repo_full_name: str
    base_branch: str
    base_sha: str
    scanned_sha: str
    head_moved: bool
    can_push: bool
    requires_fork: bool
    use_fork: bool
    branch: str
    branch_available: bool
    suggested_branch: str | None
    groups: list[FixGroup]
    excluded: list[dict[str, Any]]
    patch_checks: list[PatchCheck]
    files: dict[str, tuple[str, str]]  # path -> (original at base, final)
    combined_diff: str
    score: dict[str, Any]
    title: str
    body: str
    fingerprint: str
    blocking: list[dict[str, str]] = field(default_factory=list)

    @property
    def included_suggestion_ids(self) -> list[int]:
        return sorted(i for g in self.groups for i in g.suggestion_ids)


# ----------------------------------------------------------------------------- helpers


def default_branch_name(scan: Scan) -> str:
    return f"codeaudit/fix-{scan.id.hex[:8]}"


def _token(db: Session, user: User) -> tuple[str, GitHubIdentity]:
    identity = db.scalar(select(GitHubIdentity).where(GitHubIdentity.user_id == user.id))
    if identity is None or identity.access_token_encrypted is None:
        raise PullRequestError(
            "github_auth_required", "Connect GitHub to open pull requests.", http_status=401
        )
    try:
        return access_token(db, identity), identity
    except GitHubAuthError as exc:
        raise PullRequestError("github_auth_required", exc.message, http_status=401) from None


def _map_github_error(exc: GitHubError, *, stage: str) -> PullRequestError:
    message = (exc.details.get("github_message") or exc.message or "").lower()
    errors = " ".join(exc.details.get("github_errors", [])).lower()
    text = f"{message} {errors}"
    if isinstance(exc, GitHubAuthError):
        return PullRequestError("github_auth_required", exc.message, http_status=401)
    if (
        "protected branch" in text
        or "branch protection" in text
        or ("protected" in text and stage == "branch")
        or ("rule violation" in text and stage == "branch")
    ):
        return PullRequestError(
            "branch_protected",
            "A branch protection rule blocks creating this branch. Choose a branch name that isn't"
            " covered by the repository's protection rules, or ask a maintainer to allow it.",
        )
    if stage == "branch" and (
        "reference already exists" in text
        or isinstance(exc, GitHubValidationError)
        and "already exists" in text
    ):
        return PullRequestError(
            "branch_exists",
            "A branch with this name already exists. Preview again to get a free branch name.",
        )
    if stage == "pull_request" and "already exists" in text:
        return PullRequestError(
            "pull_request_exists", "A pull request for this branch already exists on GitHub."
        )
    if isinstance(exc, GitHubPermissionError) or (
        isinstance(exc, GitHubNotFoundError) and stage != "read"
    ):
        return PullRequestError(
            "insufficient_permissions",
            "Your GitHub account can't write to this repository. Open the pull request from a fork"
            " instead, or reconnect GitHub with private repository access if it's private.",
            http_status=403,
        )
    return PullRequestError(exc.code, exc.message, http_status=exc.http_status)


def load_groups(
    db: Session, scan: Scan, suggestion_ids: Sequence[int]
) -> tuple[list[FixGroup], list[dict[str, Any]]]:
    """Valid suggestions grouped by shared patch; everything else goes to `excluded`."""
    requested = list(dict.fromkeys(suggestion_ids))
    rows = {
        s.id: s
        for s in db.scalars(select(FixSuggestion).where(FixSuggestion.id.in_(requested))).all()
    }
    excluded: list[dict[str, Any]] = []
    grouped: OrderedDict[tuple[int | None, str], list[FixSuggestion]] = OrderedDict()
    for suggestion_id in requested:
        suggestion = rows.get(suggestion_id)
        if suggestion is None or suggestion.scan_id != scan.id:
            excluded.append(
                {"suggestion_id": suggestion_id, "reason": "not a suggestion of this scan"}
            )
        elif (
            suggestion.status is not FixStatus.READY
            or suggestion.validation_status is not ValidationStatus.VALID
            or not suggestion.patch
        ):
            excluded.append(
                {
                    "suggestion_id": suggestion_id,
                    "reason": (
                        f"patch not verified ({suggestion.validation_status.value});"
                        " only verified patches can be included"
                    ),
                }
            )
        else:
            grouped.setdefault((suggestion.llm_call_id, suggestion.patch), []).append(suggestion)
    finding_ids = {s.finding_id for group in grouped.values() for s in group}
    findings = {
        f.id: f for f in db.scalars(select(Finding).where(Finding.id.in_(finding_ids))).all()
    }
    groups = [
        FixGroup(
            members, [findings[s.finding_id] for s in members if s.finding_id in findings], patch
        )
        for (_, patch), members in grouped.items()
    ]
    return groups, excluded


def _unified(path: str, before: str, after: str) -> str:
    return "".join(
        difflib.unified_diff(
            before.splitlines(keepends=True),
            after.splitlines(keepends=True),
            f"a/{path}",
            f"b/{path}",
        )
    )


def _category(group: FixGroup) -> str:
    analyzers = {f.analyzer for f in group.findings}
    if analyzers == {"dependency"}:
        return "deps"
    if analyzers <= {"ruff"}:
        return "lint"
    return "security"


def commit_message(group: FixGroup, scan: Scan) -> str:
    severity_order = list(Severity)
    worst = (
        max(group.findings, key=lambda f: severity_order.index(f.severity))
        if group.findings
        else None
    )
    subject_detail = (
        worst.dependency.get("package")
        if worst and worst.dependency
        else (worst.rule_id.rsplit(".", 1)[-1] if worst else "issue")
    )
    paths = group.paths
    where = paths[0] if len(paths) == 1 else f"{len(paths)} files"
    subject = f"fix({_category(group)}): address {subject_detail} in {where}"[:72]
    explanation = (group.suggestions[0].explanation or "").strip()
    lines = [subject, "", *_wrap(explanation, 72), ""]
    lines += [
        f"- {f.severity.value}: {f.rule_id} ({f.file_path}:{f.start_line})" for f in group.findings
    ]
    lines += ["", "AI-generated by CodeAudit; review before merging.", f"CodeAudit-Scan: {scan.id}"]
    return "\n".join(lines)


def _s(count: int) -> str:
    return "" if count == 1 else "s"


def _wrap(text: str, width: int) -> list[str]:
    import textwrap

    return textwrap.wrap(text, width) if text else []


def render_body(
    plan_groups: list[FixGroup],
    scan: Scan,
    score: dict[str, Any],
    excluded: list[dict[str, Any]],
    checks: list[PatchCheck],
    head_moved: bool,
) -> str:
    findings = [f for g in plan_groups for f in g.findings]
    counts = Counter(f.severity.value for f in findings)
    lines = [
        "## CodeAudit fixes",
        "",
        AI_NOTICE,
        "",
        f"This pull request addresses **{len(findings)} finding{_s(len(findings))}** in"
        f" {len(plan_groups)} commit{_s(len(plan_groups))}, from the CodeAudit scan of"
        f" `{scan.commit_sha[:12] if scan.commit_sha else 'unknown'}`.",
        "",
        "### Severity breakdown",
        "",
        "| Severity | Findings fixed |",
        "|---|---|",
        *[
            f"| {severity.value} | {counts[severity.value]} |"
            for severity in reversed(list(Severity))
            if counts[severity.value]
        ],
        "",
        "### Score projection",
        "",
    ]
    if score.get("current") is None:
        lines.append("No score is available for this scan.")
    else:
        lines.append(
            f"**{score['current']:.1f}** ({score['current_grade']}) → **{score['projected']:.1f}**"
            f" ({score['projected_grade']}), {score['delta']:+.2f} points if these fixes are merged"
            f" (CodeAudit rubric v{score['rubric_version']}"
            f"{', incomplete scan' if score.get('incomplete') else ''})."
        )
    lines += ["", "### Fixes", ""]
    for index, group in enumerate(plan_groups, start=1):
        suggestion = group.suggestions[0]
        lines.append(f"#### {index}. {', '.join(sorted({f.rule_id for f in group.findings}))}")
        lines.append("")
        for finding in group.findings:
            lines.append(
                f"- **{finding.severity.value}** `{finding.file_path}:{finding.start_line}`:"
                f" {finding.message[:200]}"
            )
        lines.append("")
        if suggestion.explanation:
            lines += [suggestion.explanation.strip(), ""]
        lines.append(
            f"Confidence: {suggestion.confidence.value if suggestion.confidence else 'n/a'} ·"
            " Breaking risk:"
            f" {suggestion.breaking_risk.value if suggestion.breaking_risk else 'n/a'}"
        )
        if suggestion.test_suggestion:
            lines += ["", f"Suggested regression test: {suggestion.test_suggestion.strip()}"]
        lines.append("")
    not_applied = [c for c in checks if c.status != "applies"]
    if excluded or not_applied:
        lines += ["### Not included", ""]
        for check in not_applied:
            lines.append(
                f"- Suggestions {check.suggestion_ids} ({', '.join(check.paths)}):"
                f" {check.status.replace('_', ' ')}"
            )
        for item in excluded:
            lines.append(f"- Suggestion {item['suggestion_id']}: {item['reason']}")
        lines.append("")
    if head_moved:
        lines += [
            "The base branch has moved since the scanned commit; every included patch was"
            " re-checked"
            " against its current head.",
            "",
        ]
    lines.append(
        "<sub>Opened with CodeAudit after explicit confirmation by the repository user.</sub>"
    )
    return "\n".join(lines)


def _fingerprint(
    base_sha: str, head_repo: str, branch: str, use_fork: bool, groups: list[FixGroup]
) -> str:
    material = json.dumps(
        {
            "base_sha": base_sha,
            "head_repo": head_repo,
            "branch": branch,
            "use_fork": use_fork,
            "groups": [
                [g.suggestion_ids, hashlib.sha256(g.patch.encode()).hexdigest()] for g in groups
            ],
        },
        sort_keys=True,
    )
    return hashlib.sha256(material.encode()).hexdigest()


