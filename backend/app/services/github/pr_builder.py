def _ensure_fork(
    github: GitHubClient, owner: str, name: str, login: str, base_branch: str, default_branch: str
) -> None:
    try:
        existing = github.get_repo(login, name)
        if existing.fork:
            return
        raise PullRequestError(
            "fork_name_taken",
            f"You already have a repository named {login}/{name} that isn't a fork of"
            f" {owner}/{name}.",
        )
    except GitHubNotFoundError:
        pass
    github.create_fork(owner, name, default_branch_only=base_branch == default_branch)
    deadline = time.monotonic() + get_settings().github_fork_wait_seconds
    while True:  # forks are created asynchronously
        try:
            github.get_branch_head(login, name, base_branch)
            return
        except GitHubNotFoundError:
            if time.monotonic() > deadline:
                raise PullRequestError(
                    "fork_not_ready", "GitHub is still creating your fork. Try again in a minute."
                ) from None
            time.sleep(2)


def create_pull_request_from_preview(
    db: Session,
    preview: PullRequest,
    scan: Scan,
    user: User,
    *,
    github: GitHubClient | None = None,
) -> PullRequest:
    """Create the branch, commits and pull request for a confirmed preview.

    The plan is rebuilt first; if it no longer matches what the user previewed
    (base moved, patches changed, branch taken), nothing is written.
    """
    if preview.status is not PullRequestStatus.CREATING or preview.confirmed_at is None:
        raise PullRequestError("not_confirmed", "This pull request has not been confirmed.")
    token, identity = _token(db, user)
    client = github or GitHubClient(token)
    try:
        plan = build_plan(
            db,
            scan,
            user,
            preview.included_suggestion_ids,
            branch=preview.branch,
            use_fork=preview.use_fork,
            github=client,
        )
        if plan.fingerprint != preview.preview_fingerprint:
            raise PullRequestError(
                "preview_outdated",
                "The repository or the selected fixes changed after the preview (for example new"
                " commits on the base branch). Open a new preview and confirm again.",
                details={"head_moved": plan.head_moved, "blocking": plan.blocking},
            )
        blocking = [
            b for b in plan.blocking if not (b["code"] == "fork_required" and plan.use_fork)
        ]
        if blocking:
            raise PullRequestError(
                blocking[0]["code"], blocking[0]["message"], details={"blocking": blocking}
            )

        owner, name = plan.repo_full_name.split("/")
        head_owner, head_name = plan.head_repo_full_name.split("/")
        stage = "fork"
        try:
            if plan.use_fork:
                repo = client.get_repo(owner, name)
                _ensure_fork(
                    client, owner, name, identity.login, plan.base_branch, repo.default_branch
                )

            stage = "commits"
            parent = plan.base_sha
            try:
                tree = client.get_commit_tree(head_owner, head_name, parent)
            except (GitHubNotFoundError, GitHubValidationError):
                if not plan.use_fork:
                    raise
                # An older fork may not have the base commit yet.
                client.sync_fork(head_owner, head_name, plan.base_branch)
                tree = client.get_commit_tree(head_owner, head_name, parent)
            commits: list[dict[str, Any]] = []
            # Replay each group's change on top of the previous commit.
            with tempfile.TemporaryDirectory(prefix="codeaudit-pr-") as tmp:
                work = Path(tmp)
                for path, (before, _) in plan.files.items():
                    (work / path).parent.mkdir(parents=True, exist_ok=True)
                    (work / path).write_text(before, encoding="utf-8", errors="surrogateescape")
                for group in plan.groups:
                    ok, error = apply_patch_in_place(work, group.patch)
                    if not ok:  # can't happen if the plan matched; never force
                        raise PullRequestError(
                            "merge_conflict", f"A patch stopped applying: {error}"
                        )
                    entries = {
                        path: (
                            client.create_blob(
                                head_owner,
                                head_name,
                                (work / path).read_text(encoding="utf-8", errors="surrogateescape"),
                            ),
                            client.get_file_mode(head_owner, head_name, plan.base_sha, path),
                        )
                        for path in group.paths
                    }
                    tree = client.create_tree(head_owner, head_name, tree, entries)
                    parent = client.create_commit(
                        head_owner, head_name, commit_message(group, scan), tree, parent
                    )
                    commits.append(
                        {
                            "sha": parent,
                            "message": commit_message(group, scan).split("\n", 1)[0],
                            "suggestion_ids": group.suggestion_ids,
                        }
                    )

            stage = "branch"
            client.create_branch(head_owner, head_name, plan.branch, parent)
            stage = "pull_request"
            head_ref = plan.branch if head_owner == owner else f"{head_owner}:{plan.branch}"
            created = client.create_pull_request(
                owner,
                name,
                title=preview.title,
                body=with_ai_notice(preview.body),
                head=head_ref,
                base=plan.base_branch,
            )
        except GitHubError as exc:
            raise _map_github_error(exc, stage=stage) from None
    finally:
        if github is None:
            client.close()

    preview.status = PullRequestStatus.OPEN
    preview.commits = commits
    preview.pr_number = int(created["number"])
    preview.pr_url = str(created["html_url"])
    preview.error_code = preview.error_message = None
    db.commit()
    logger.info("scan %s: opened %s with %d commits", scan.id, preview.pr_url, len(commits))
    return preview


def preview_details(plan: PullRequestPlan, scan: Scan) -> dict[str, Any]:
    """Plan fields shown in the preview, beyond what the PullRequest row stores."""
    return {
        "scanned_sha": plan.scanned_sha,
        "head_moved": plan.head_moved,
        "can_push": plan.can_push,
        "requires_fork": plan.requires_fork,
        "branch_available": plan.branch_available,
        "suggested_branch": plan.suggested_branch,
        "files": [
            {"path": path, "original": before, "patched": after}
            for path, (before, after) in sorted(plan.files.items())
        ],
        "planned_commits": [
            {
                "message": commit_message(group, scan),
                "suggestion_ids": group.suggestion_ids,
                "paths": group.paths,
            }
            for group in plan.groups
        ],
        "patch_checks": [dataclasses.asdict(check) for check in plan.patch_checks],
        "excluded": plan.excluded,
        "blocking": plan.blocking,
        "score": plan.score,
        "writes_to": plan.head_repo_full_name,
    }


def with_ai_notice(body: str) -> str:
    """The AI-generated warning can't be edited out of the pull request body."""
    return body if AI_NOTICE in body else f"{AI_NOTICE}\n\n{body}"
