def build_plan(
    db: Session,
    scan: Scan,
    user: User,
    suggestion_ids: Sequence[int],
    *,
    branch: str | None = None,
    use_fork: bool = False,
    github: GitHubClient | None = None,
) -> PullRequestPlan:
    """Everything the PR would contain, computed against GitHub's current state. Read-only."""
    if scan.source is not ScanSource.GITHUB or not (
        scan.repo_owner and scan.repo_name and scan.commit_sha
    ):
        raise PullRequestError(
            "not_a_repository_scan",
            "Pull requests can only be opened for scans of a GitHub repository.",
            http_status=400,
        )
    groups, excluded = load_groups(db, scan, suggestion_ids)
    if not groups:
        raise PullRequestError(
            "no_valid_suggestions",
            "None of the selected suggestions has a verified patch.",
            http_status=422,
            details={"excluded": excluded},
        )

    token, identity = _token(db, user)
    client = github or GitHubClient(token)
    owner, name = scan.repo_owner, scan.repo_name
    try:
        repo = client.get_repo(owner, name)
        base_branch = (
            scan.repo_ref if scan.repo_ref and not SHA.match(scan.repo_ref) else repo.default_branch
        )
        try:
            base_sha = client.get_branch_head(owner, name, base_branch)
        except GitHubNotFoundError:  # the scan was of a tag or the branch is gone
            base_branch = repo.default_branch
            base_sha = client.get_branch_head(owner, name, base_branch)
        head_moved = base_sha != scan.commit_sha

        # Reproduce every change on the current base, fix group by fix group.
        originals: dict[str, str | None] = {}
        for group in groups:
            for path in group.paths:
                if path not in originals:
                    originals[path] = client.get_file(owner, name, path, base_sha)
    except GitHubError as exc:
        raise _map_github_error(exc, stage="read") from None
    finally:
        if github is None:
            client.close()

    checks: list[PatchCheck] = []
    applied_groups: list[FixGroup] = []
    with tempfile.TemporaryDirectory(prefix="codeaudit-pr-") as tmp:
        work = Path(tmp)
        for path, content in originals.items():
            if content is not None:
                (work / path).parent.mkdir(parents=True, exist_ok=True)
                (work / path).write_text(content, encoding="utf-8", errors="surrogateescape")
        for group in groups:
            missing = [p for p in group.paths if originals.get(p) is None]
            if missing:
                checks.append(
                    PatchCheck(
                        group.suggestion_ids,
                        group.paths,
                        "no_longer_applies",
                        f"{', '.join(missing)} no longer exists on {base_branch}",
                    )
                )
                continue
            snapshot = {
                p: (work / p).read_text(encoding="utf-8", errors="surrogateescape")
                for p in group.paths
            }
            ok, error = apply_patch_in_place(work, group.patch)
            if not ok:
                # Validated against the scanned commit: failing now means the base moved or
                # an earlier selected fix changed the same lines.
                touched_by_earlier = any(set(group.paths) & set(g.paths) for g in applied_groups)
                status = (
                    "conflicts" if touched_by_earlier and not head_moved else "no_longer_applies"
                )
                checks.append(PatchCheck(group.suggestion_ids, group.paths, status, error))
                continue
            broken = next(
                (
                    err
                    for p in group.paths
                    if (
                        err := syntax_error(
                            p, (work / p).read_text(encoding="utf-8", errors="surrogateescape")
                        )
                    )
                ),
                None,
            )
            if broken:
                for path, content in snapshot.items():
                    (work / path).write_text(content, encoding="utf-8", errors="surrogateescape")
                checks.append(PatchCheck(group.suggestion_ids, group.paths, "syntax_error", broken))
                continue
            checks.append(PatchCheck(group.suggestion_ids, group.paths, "applies"))
            applied_groups.append(group)
        files = {
            path: (
                originals[path] or "",
                (work / path).read_text(encoding="utf-8", errors="surrogateescape"),
            )
            for path in originals
            if originals[path] is not None and any(path in g.paths for g in applied_groups)
        }

    blocking: list[dict[str, str]] = []
    if not applied_groups:
        blocking.append(
            {
                "code": "stale_head" if head_moved else "merge_conflict",
                "message": "None of the selected patches applies to the current base branch.",
            }
        )

    requires_fork = not bool(repo.can_push)
    head_repo = f"{identity.login}/{name}" if use_fork else f"{owner}/{name}"
    if requires_fork and not use_fork:
        blocking.append(
            {
                "code": "fork_required",
                "message": (
                    f"Your GitHub account ({identity.login}) can't push to {owner}/{name}."
                    " Confirm opening the pull request from a fork."
                ),
            }
        )

    wanted = branch or default_branch_name(scan)
    branch_available, suggested = True, None
    with GitHubClient(token) if github is None else _nullcontext(github) as reader:
        try:
            head_owner, head_name = head_repo.split("/")
            if reader.branch_exists(head_owner, head_name, wanted):
                branch_available = False
                for suffix in range(2, MAX_BRANCH_SUFFIX + 2):
                    candidate = f"{wanted}-{suffix}"
                    if not reader.branch_exists(head_owner, head_name, candidate):
                        suggested = candidate
                        break
        except GitHubNotFoundError:
            pass  # the fork doesn't exist yet: every name is free
        except GitHubError as exc:
            raise _map_github_error(exc, stage="read") from None
    if not branch_available:
        blocking.append(
            {
                "code": "branch_exists",
                "message": f"Branch {wanted} already exists in {head_repo}."
                + (f" Use {suggested}." if suggested else ""),
            }
        )

    finding_ids = [f.id for g in applied_groups for f in g.findings]
    projection = project(db, scan, finding_ids)
    score = {
        "current": projection.current.overall,
        "current_grade": projection.current.grade,
        "projected": projection.projected.overall,
        "projected_grade": projection.projected.grade,
        "delta": projection.delta,
        "rubric_version": projection.current.rubric_version,
        "incomplete": projection.current.incomplete,
    }
    count = len(finding_ids)
    kinds = sorted({_category(g) for g in applied_groups})
    title = (
        f"CodeAudit: fix {count} finding{'s' if count != 1 else ''} ({', '.join(kinds)})"
        if applied_groups
        else "CodeAudit fixes"
    )
    return PullRequestPlan(
        repo_full_name=f"{owner}/{name}",
        head_repo_full_name=head_repo,
        base_branch=base_branch,
        base_sha=base_sha,
        scanned_sha=scan.commit_sha,
        head_moved=head_moved,
        can_push=not requires_fork,
        requires_fork=requires_fork,
        use_fork=use_fork,
        branch=wanted,
        branch_available=branch_available,
        suggested_branch=suggested,
        groups=applied_groups,
        excluded=excluded,
        patch_checks=checks,
        files=files,
        combined_diff="".join(
            _unified(p, before, after) for p, (before, after) in sorted(files.items())
        ),
        score=score,
        title=title,
        body=render_body(applied_groups, scan, score, excluded, checks, head_moved),
        fingerprint=_fingerprint(base_sha, head_repo, wanted, use_fork, applied_groups),
        blocking=blocking,
    )


class _nullcontext:
    def __init__(self, value: GitHubClient) -> None:
        self.value = value

    def __enter__(self) -> GitHubClient:
        return self.value

    def __exit__(self, *_: object) -> None:
        return None


def save_preview(db: Session, scan: Scan, user: User, plan: PullRequestPlan) -> PullRequest:
    row = PullRequest(
        scan_id=scan.id,
        user_id=user.id,
        status=PullRequestStatus.PREVIEWED,
        repo_full_name=plan.repo_full_name,
        head_repo_full_name=plan.head_repo_full_name,
        base_branch=plan.base_branch,
        base_sha=plan.base_sha,
        branch=plan.branch,
        use_fork=plan.use_fork,
        title=plan.title,
        body=plan.body,
        included_suggestion_ids=plan.included_suggestion_ids,
        preview_fingerprint=plan.fingerprint,
        combined_diff=plan.combined_diff,
    )
    db.add(row)
    db.commit()
    return row


