"""Fix pull requests: build a preview, and only on explicit confirmation write to GitHub.

Guarantees:
- Only suggestions whose patch was validated (`validation_status == valid`) are used.
- Patches are re-applied to the *current* head of the base branch. If the branch
  moved since the scan, each patch is re-checked there; patches that no longer
  apply (or that conflict with another selected fix) are reported and left out,
  never forced.
- One commit per logical fix group, on a new branch `codeaudit/fix-<scan>`.
- `create_pull_request_from_preview` is the only function here that writes to
  GitHub, and it refuses to run unless the plan still matches the fingerprint of
  the preview the user confirmed. Nothing in scanning or enrichment calls it.
"""

